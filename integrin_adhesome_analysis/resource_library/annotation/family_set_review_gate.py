#!/usr/bin/env python3
"""Conservative post-classification gate for reconciled adhesome family_set hypotheses.

Input: TSV with a family_set or assigned_family column. This tool does NOT infer family
identities from gene symbols or calibration accessions. It only annotates the strength
and admissibility of identities generated by the upstream classifier.

Usage:
  python family_set_review_gate.py candidate_hypotheses.tsv gated.tsv \
      --registry family_set_registry_reconciled.json

Important: 'CDD specific' must reflect NCBI-specific model evidence, not a regex text
hit; no automatic protein-specific orthology inference is implemented here.
"""

# Resolve source resources independently of the caller working directory.
import sys as _layout_sys
from pathlib import Path as _LayoutPath
_LAYOUT_BUNDLE_ROOT = next(p for p in _LayoutPath(__file__).resolve().parents
                          if (p/'config/layout_paths.json').is_file() and (p/'pipeline_paths.py').is_file())
if str(_LAYOUT_BUNDLE_ROOT) not in _layout_sys.path:
    _layout_sys.path.insert(0, str(_LAYOUT_BUNDLE_ROOT))
from pipeline_paths import activate as _layout_activate, resource_path as _layout_resource
_layout_activate()

import argparse
import csv
import json
from pathlib import Path

TRUE = {'true', '1', 'yes', 'y'}
FALSE = {'false', '0', 'no', 'n'}


def truth(value):
    if value is True: return True
    if value is False: return False
    if value is None: return None
    txt = str(value).strip().lower()
    if txt in TRUE: return True
    if txt in FALSE: return False
    return None


def gate(row, registry, phylogenetic_identity_resolution=False):
    families = registry['family_sets']
    fam = str(row.get('family_set') or row.get('assigned_family') or row.get('family') or '').strip()
    original_family=fam
    if fam in ('src','Src','SRC'):fam='Src'
    rule = families.get(fam) or (families.get('SRC') if fam=='Src' else None)
    flags = []
    if not fam or fam.lower() in ('unassigned', 'unresolved', 'none'):
        flags.append('NO_FAMILY_SET_HYPOTHESIS')
    elif not rule:
        flags.append('FAMILY_SET_OUTSIDE_CALIBRATION_REGISTRY')
    else:
        flags.extend(rule.get('review_flags', []))
    # Never mistake an absent evidence field for a negative or a positive.
    architecture = truth(row.get('stage2_architecture_compatible'))
    cdd = truth(row.get('stage2_cdd_pattern_match'))
    curated = truth(row.get('stage2_named_curated_cd_match'))
    specific_hit = truth(row.get('ncbi_cdd_specific_hit_threshold_met'))
    if architecture is False: flags.append('STAGE2_ARCHITECTURE_CONTRADICTION')
    elif architecture is None: flags.append('STAGE2_ARCHITECTURE_NOT_PROVIDED')
    if cdd is False: flags.append('STAGE2_NAMED_CDD_PATTERN_NOT_MATCHED')
    elif cdd is None: flags.append('STAGE2_NAMED_CDD_PATTERN_NOT_PROVIDED')
    if curated is False: flags.append('CURATED_CDD_NAME_NOT_MATCHED')
    elif curated is None: flags.append('CURATED_CDD_NAME_NOT_PROVIDED')
    if specific_hit is not True:
        flags.append('NCBI_SPECIFIC_HIT_THRESHOLD_NOT_INDEPENDENTLY_VERIFIED')
    # Other-specific reference and duplication-aware phylogenetic support remains mandatory
    # for one-to-one protein orthology and paralog names.
    phylo = truth(row.get('paralog_resolving_phylogeny_supported'))
    if phylogenetic_identity_resolution and phylo is not True: flags.append('PARALOG_RESOLUTION_NOT_VERIFIED')
    flags = list(dict.fromkeys(flags))
    manual = str(row.get('review_decision') or '').strip().upper()
    if manual in ('REJECT', 'RE-ANNOTATE'):
        final_status = 'REJECT_OR_REANNOTATE'; needs_review = True
    elif fam and rule and all(x is True for x in (architecture, cdd, curated, specific_hit)) and not rule.get('user_inspection_required'):
        # Still requires orthology evidence before issuing an individual protein name.
        final_status = 'FAMILY_HYPOTHESIS_SUPPORTED;ORTHOLOGY_UNVALIDATED'
        needs_review = bool(phylogenetic_identity_resolution and phylo is not True)
    elif fam and rule:
        final_status = 'PROVISIONAL_FAMILY_SET_USER_INSPECTION_REQUIRED'
        needs_review = True
    else:
        final_status = 'UNRESOLVED_FAMILY_SET_USER_INSPECTION_REQUIRED'
        needs_review = True
    out = dict(row)
    out.update({
        'gated_family_set': fam if rule else '',
        'input_family_set': original_family,
        'family_set_acceptance_status': final_status,
        'user_inspection_required': str(needs_review).lower(),
        'no_auto_protein_identity': str(needs_review).lower(),
        'phylogenetic_identity_resolution': 'requested' if phylogenetic_identity_resolution else 'not_requested',
        'paralog_identity_status': 'not_evaluated' if not phylogenetic_identity_resolution else 'supported' if phylo is True else 'unresolved',
        'family_set_review_flags': ';'.join(flags),
        'calibration_basis': 'Calibration-positive reference rules; independent validation pending'
    })
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('input', type=Path, help='TSV with upstream family_set hypotheses')
    ap.add_argument('output', type=Path, help='TSV with conservative identity-review flags')
    reconciled=_layout_resource(Path(__file__).with_name('family_set_registry_reconciled.json'))
    ap.add_argument('--registry', type=Path, default=reconciled if _layout_resource(reconciled).is_file() else _layout_resource(Path(__file__).with_name('family_set_registry.json')))
    ap.add_argument('--phylogenetic-identity-resolution',action='store_true',help='Optional paralog review; absent phylogeny does not invalidate family support')
    a = ap.parse_args()
    reg = json.loads(_layout_resource(a.registry).read_text(encoding='utf-8'))
    with _layout_resource(a.input).open(newline='', encoding='utf-8-sig') as h:
        reader = csv.DictReader(h, delimiter='\t')
        if not reader.fieldnames or not ({'family_set','assigned_family','family'} & set(reader.fieldnames)):
            ap.error('Input needs family_set, assigned_family or family field')
        records = [gate(r, reg,a.phylogenetic_identity_resolution) for r in reader]
    fields = list(dict.fromkeys(reader.fieldnames + [
        'gated_family_set','family_set_acceptance_status','user_inspection_required',
        'no_auto_protein_identity','family_set_review_flags','calibration_basis',
        'phylogenetic_identity_resolution','paralog_identity_status','input_family_set']))
    a.output.parent.mkdir(parents=True, exist_ok=True)
    with _layout_resource(a.output).open('w', newline='', encoding='utf-8') as h:
        writer = csv.DictWriter(h, fieldnames=fields, delimiter='\t', extrasaction='ignore')
        writer.writeheader();writer.writerows(records)
    print(f'{len(records)} hypotheses gated; file: {a.output}')

if __name__ == '__main__': main()
