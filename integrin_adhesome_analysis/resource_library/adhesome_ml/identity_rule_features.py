"""Sequence-only measurable features from Stage 2 family identity rules."""
import json
import re
from functools import lru_cache
from pathlib import Path


@lru_cache(maxsize=4)
def load_rules(path):
    data=json.loads(Path(path).read_text(encoding='utf-8-sig'))
    return data.get('rules',[]),data.get('pfam_cdd_aliases',{}),data.get('additional_cdd_domains',{})


def _matches(pattern,text):
    try: return bool(re.search(pattern,str(text),re.I))
    except re.error: return False


def features(row, cdd_features, rule_path, domain_parser):
    rules,pfam_aliases,additional=load_rules(str(rule_path))
    hits=domain_parser(row)
    # CDD reference annotations are rule-measurable sequence-domain evidence. Their
    # aggregate hit count and query positions are generated by the same BLAST step.
    cdd_domains=[]
    annotations={}
    for key,value in cdd_features.items():
        m=re.match(r'^cdd:annotation:([^:]+):(hit_count|n_start|c_end|best_bitscore|best_identity|query_coverage)$',key)
        if m: annotations.setdefault(m.group(1),{})[m.group(2)]=value
    for token,vals in annotations.items():
        if vals.get('hit_count',0)>0:
            cdd_domains.append({'id':token,'name':token,'start':vals.get('n_start'),'end':vals.get('c_end'),
                'count':vals.get('hit_count',0),'source':'cdd_reference_similarity'})
    domains=[*hits,*cdd_domains]
    length=float(row.get('ml_seq_len_aa') or 0)
    output={}
    for rule in rules:
        rid=rule.get('id','unknown'); prefix=f'identity_rule:{rid}:'
        groups=rule.get('required_groups',[]); group_hits=[]; satisfied=[]
        for index,group in enumerate(groups):
            models=[str(x) for x in group.get('models',[])]
            count_required=float(group.get('count',1))
            matched=[]
            for domain in domains:
                for model in models:
                    name=str(domain.get('name','')); accession=str(domain.get('id',''))
                    match=accession.casefold()==model.casefold() or name.casefold()==model.casefold()
                    if model in pfam_aliases and _matches(pfam_aliases[model],name): match=True
                    if model in additional and _matches(additional[model],name): match=True
                    if match:
                        n=max(1,int(domain.get('count',1) or 1))
                        matched.extend([domain]*n)
                        break
            group_hits.append(matched); ok=len(matched)>=count_required; satisfied.append(ok)
            output[prefix+f'group_{index}_count']=float(len(matched))
            output[prefix+f'group_{index}_required_count']=count_required
            output[prefix+f'group_{index}_present']=float(bool(matched))
            output[prefix+f'group_{index}_satisfied']=float(ok)
        output[prefix+'required_group_count']=float(len(groups))
        output[prefix+'required_satisfied_count']=float(sum(satisfied))
        output[prefix+'required_satisfied_fraction']=(sum(satisfied)/len(satisfied)) if satisfied else 0.0
        output[prefix+'required_all_satisfied']=float(bool(satisfied) and all(satisfied))
        order=rule.get('ordered_groups',[]); order_ok=False
        if order and all(isinstance(i,int) and 0<=i<len(group_hits) and group_hits[i] for i in order):
            positions=[]
            for i in order:
                starts=[float(x['start']) for x in group_hits[i] if x.get('start') not in (None,'')]
                positions.append(min(starts) if starts else None)
            order_ok=all(x is not None for x in positions) and all(a<=b for a,b in zip(positions,positions[1:]))
        output[prefix+'ordered_group_count']=float(len(order))
        output[prefix+'ordered_groups_satisfied']=float(order_ok)
        pattern=rule.get('specific_cdd_pattern','')
        pattern_hits=[]
        if pattern and pattern!='(?!)':
            pattern_hits=[d for d in domains if _matches(pattern,d.get('name',''))]
        output[prefix+'specific_cdd_pattern_defined']=float(bool(pattern and pattern!='(?!)'))
        output[prefix+'specific_cdd_pattern_hit_count']=float(len(pattern_hits))
        output[prefix+'specific_cdd_pattern_present']=float(bool(pattern_hits))
        maxima=rule.get('maximum_model_counts',{}) or {}
        max_satisfied=[]
        for model,maximum in maxima.items():
            observed=sum(1 for d in domains if str(d.get('id','')).casefold()==str(model).casefold() or str(d.get('name','')).casefold()==str(model).casefold())
            output[prefix+f'max_{model}_observed_count']=float(observed)
            output[prefix+f'max_{model}_limit']=float(maximum)
            output[prefix+f'max_{model}_satisfied']=float(observed<=float(maximum))
            max_satisfied.append(observed<=float(maximum))
        output[prefix+'maximum_constraints_satisfied']=float(all(max_satisfied)) if max_satisfied else 1.0
        lr=rule.get('length_range')
        if isinstance(lr,(list,tuple)) and len(lr)==2:
            output[prefix+'length_in_range']=float(length>0 and float(lr[0])<=length<=float(lr[1]))
            output[prefix+'length_range_min']=float(lr[0]); output[prefix+'length_range_max']=float(lr[1])
        repeats=rule.get('required_cdd_repeat_indices',[]) or []
        repeat_matches=0
        for name in repeats:
            repeat_matches+=sum(1 for d in domains if _matches(r'(?<![A-Za-z0-9])'+re.escape(str(name))+r'(?![A-Za-z0-9])',d.get('name','')))
        if repeats:
            output[prefix+'required_cdd_repeat_count']=float(len(repeats))
            output[prefix+'required_cdd_repeat_matched']=float(repeat_matches)
            output[prefix+'required_cdd_repeats_satisfied']=float(repeat_matches>=len(repeats))
    return output
